//! Generates the Markdown reader's Unicode tables (development tool, never
//! shipped). Inputs are downloaded by hand and not committed:
//!
//! ```text
//! curl -LO https://html.spec.whatwg.org/entities.json
//! cargo run -p gen-entities -- entities entities.json > crates/doc/src/md/entities.rs
//!
//! curl -LO https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt
//! cargo run -p gen-entities -- punct UnicodeData.txt > crates/doc/src/md/punct.rs
//! ```

use std::fmt::Write;
use std::process::ExitCode;

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().collect();
    let out = match args.get(1..) {
        Some([cmd, path]) if cmd == "entities" => read(path).and_then(|s| entities(&s)),
        Some([cmd, path]) if cmd == "punct" => read(path).and_then(|s| punct(&s)),
        _ => Err("usage: gen-entities entities <entities.json> | punct <UnicodeData.txt>".into()),
    };
    match out {
        Ok(s) => {
            print!("{s}");
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("gen-entities: {e}");
            ExitCode::FAILURE
        }
    }
}

fn read(path: &str) -> Result<String, String> {
    std::fs::read_to_string(path).map_err(|e| format!("{path}: {e}"))
}

/// The WHATWG named character references that end with `;` (the only form
/// CommonMark accepts), as a table sorted by name for binary search.
fn entities(json: &str) -> Result<String, String> {
    let v: serde_json::Value = serde_json::from_str(json).map_err(|e| e.to_string())?;
    let map = v.as_object().ok_or("entities.json: not an object")?;
    let mut table: Vec<(&str, &str)> = Vec::new();
    for (key, val) in map {
        let Some(name) = key.strip_prefix('&').and_then(|k| k.strip_suffix(';')) else {
            continue;
        };
        let chars = val["characters"]
            .as_str()
            .ok_or_else(|| format!("{key}: no characters"))?;
        table.push((name, chars));
    }
    table.sort_unstable();
    let mut s = String::from(
        "//! HTML5 named character references (generated; do not edit).\n\
         //! Source: https://html.spec.whatwg.org/entities.json, the names that\n\
         //! end with `;`, without `&` and `;`, sorted for binary search.\n\
         //! Generated by:\n\
         //! `cargo run -p gen-entities -- entities entities.json > crates/doc/src/md/entities.rs`\n\n\
         pub(super) static ENTITIES: &[(&str, &str)] = &[\n",
    );
    for (name, chars) in &table {
        writeln!(s, "    ({name:?}, {chars:?}),").unwrap();
    }
    s.push_str("];\n");
    Ok(s)
}

/// Non-ASCII code points of the Unicode general categories P* and S*
/// (CommonMark's "Unicode punctuation character"), as sorted ranges.
fn punct(data: &str) -> Result<String, String> {
    let mut ranges: Vec<(u32, u32)> = Vec::new();
    for line in data.lines() {
        let mut f = line.split(';');
        let (Some(cp), Some(name), Some(cat)) = (f.next(), f.next(), f.next()) else {
            return Err(format!("bad line: {line}"));
        };
        if !(cat.starts_with('P') || cat.starts_with('S')) {
            continue;
        }
        if name.ends_with(", First>") || name.ends_with(", Last>") {
            return Err(format!("unexpected range entry in P/S: {line}"));
        }
        let cp = u32::from_str_radix(cp, 16).map_err(|e| format!("{line}: {e}"))?;
        if cp < 0x80 {
            continue;
        }
        match ranges.last_mut() {
            Some((_, hi)) if *hi + 1 == cp => *hi = cp,
            _ => ranges.push((cp, cp)),
        }
    }
    let mut s = String::from(
        "//! Non-ASCII Unicode punctuation for emphasis flanking: general\n\
         //! categories P* and S* (generated; do not edit). ASCII punctuation is\n\
         //! checked with `is_ascii_punctuation`.\n\
         //! Source: https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt\n\
         //! Generated by:\n\
         //! `cargo run -p gen-entities -- punct UnicodeData.txt > crates/doc/src/md/punct.rs`\n\n\
         /// Sorted, disjoint, inclusive ranges.\n\
         pub(super) static PUNCT: &[(char, char)] = &[\n",
    );
    for (lo, hi) in &ranges {
        writeln!(s, "    ('\\u{{{lo:x}}}', '\\u{{{hi:x}}}'),").unwrap();
    }
    s.push_str("];\n");
    Ok(s)
}
